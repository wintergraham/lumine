#!/usr/bin/env python3
"""Reproduce the bounded native source-paint subset from vendored pinned Skia.
No pixels, browser process, target output, or external source download is read.
"""
from pathlib import Path
import hashlib,json
root=Path(__file__).resolve().parents[1]
source=root/'vendor/skia154-source-paint'
manifest=json.loads((source/'provenance.json').read_text())
for item in manifest['files']+manifest.get('blinkPaintDerivation',[]):
    assert hashlib.sha256((source/item['localPath']).read_bytes()).hexdigest()==item['sha256']
assert '#define SK_SUPPORT_LEGACY_CONIC_CHOP' in (source/'ChromiumSkUserConfig.h').read_text()
h=(source/'SkAnalyticEdge.h').read_text();e=(source/'SkAnalyticEdge.cpp').read_text();a=(source/'SkScan_AAAPath.cpp').read_text()
compat=(root/'vendor/skia154-source-paint/compat.inc').read_text()
snap_start=a.index('SkAlpha snapAlpha(')
compat=compat.replace('// SOURCE_RUN_BASED_ALPHA_SNAP','static '+a[snap_start:a.index('\n',snap_start)])
header=h[h.index('struct SkAnalyticEdge {'):h.index('\n#endif',h.index('struct SkAnalyticCubicEdge'))]
start=e.index('bool SkAnalyticQuadraticEdge::updateQuadratic()');end=e.index('\n}',start)+2
edge=e[e.index('static constexpr int kInverseTableSize'):end]
walker=a[a.index('static SkAlpha trapezoid_to_alpha'):a.index('\nstatic void check_intersection',a.index('static void aaa_walk_convex_edges'))]
bridge=(source/'bridge.inc').read_text()
geometry=(source/'SkGeometry.cpp').read_text();clipping=(source/'SkEdgeClipper.cpp').read_text()
clip=(source/'clip.inc').read_text()
clip_geometry=geometry[geometry.index('int valid_unit_divide('):geometry.index('} // namespace',geometry.index('int valid_unit_divide('))]
clip_geometry+=geometry[geometry.index('int SkFindUnitQuadRoots('):geometry.index('\n///////////////////////////////////////////////////////////////////////////////',geometry.index('int SkFindUnitQuadRoots('))]
clip_geometry+=geometry[geometry.index('static inline float2 interp('):geometry.index('\nvoid SkChopQuadAtHalf(',geometry.index('static inline float2 interp('))]
clip=clip.replace('// SOURCE_CLIPPING_GEOMETRY',clip_geometry)
clip_helpers=clipping[clipping.index('static inline void clamp_le('):clipping.index('\nbool SkEdgeClipper::clipLine(')]
clip_helpers+=clipping[clipping.index('static bool chopMonoQuadAt('):clipping.index('\nbool SkEdgeClipper::clipQuad(')]
clip=clip.replace('// SOURCE_CLIPPING_MONO_QUADS',clip_helpers)
output='''// Generated by scripts/prepare-source-skia154.py from pinned Skia 2466dcf.
// Copyright 2006/2016 The Android Open Source Project; BSD license and exact
// upstream source hashes are retained in vendor/skia154-source-paint/.
// Only a bounded native geometry-to-coverage ABI is exposed. No pixel inputs.
'''+compat+header+edge+walker+clip+bridge
(root/'crates/lumine-gpu/src/source_skia154.cpp').write_text(output)
